import type { SpeakingPart } from "../validation/polish-request";

const PART_PROMPTS: Record<SpeakingPart, string> = {
  1: `
Part 1：回答熟悉话题或个人经历。
通常采用“直接回答 → 一个清楚的原因 → 有用时补充一个小细节或例子”。
保持简洁、个人化、直接和有对话感，内容通常适合约 15–30 秒自然表达。
不要过度分析，不要写长引言、正式结论或迷你议论文。
`.trim(),
  2: `
Part 2：帮助学习者形成连贯的个人长段表达。
根据题意灵活组织“背景 → 人物／事物／地点 → 发展 → 具体细节 → 感受或反思 → 意义”，不要机械套用所有环节。
通过解释、背景、感受、后果和已提供事实之间的联系来扩展，使内容能够支持约 1 分 45 秒至 2 分钟的自然表达。
不要为了拉长答案而虚构具体人生经历。
`.trim(),
  3: `
Part 3：处理更广泛或抽象的问题，重点是推理而非作文结构。
根据需要灵活运用“立场、原因、解释、例子、因果、比较、限定、另一种观点、结论”，不要求每项都出现。
在合适时超越个人偏好，说明为什么、发展因果关系、承认复杂性并自然限定观点。
答案需要有足够推理，但不要变成长篇演讲或议论文。
`.trim(),
};

export function getPartPrompt(part: SpeakingPart) {
  return PART_PROMPTS[part];
}
